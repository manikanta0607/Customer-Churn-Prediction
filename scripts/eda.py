"""Exploratory data analysis: saves figures and a data-driven Markdown report."""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from churn_prediction import config, data, features  # noqa: E402

REPORT = config.ROOT / "docs" / "reports" / "EDA_REPORT.md"
PALETTE = {0: "#4C78A8", 1: "#E4572E"}


def rate_by(df: pd.DataFrame, col: str) -> pd.DataFrame:
    g = df.groupby(col, observed=True)[config.TARGET].agg(["mean", "count"])
    return g.rename(columns={"mean": "churn_rate", "count": "customers"}).sort_values("churn_rate", ascending=False)


def save(fig, name: str) -> None:
    config.IMAGES_DIR.mkdir(parents=True, exist_ok=True)
    fig.tight_layout()
    fig.savefig(config.IMAGES_DIR / name, dpi=130)
    plt.close(fig)


def bar_rate(df: pd.DataFrame, col: str, title: str, name: str) -> pd.DataFrame:
    r = rate_by(df, col)
    fig, ax = plt.subplots(figsize=(6.5, 3.8))
    bars = ax.bar(r.index.astype(str), r["churn_rate"] * 100, color=PALETTE[1])
    ax.set_ylabel("Churn rate (%)")
    ax.set_title(title)
    ax.axhline(df[config.TARGET].mean() * 100, color="grey", ls="--", lw=1, label="Overall")
    ax.legend()
    plt.setp(ax.get_xticklabels(), rotation=20, ha="right")
    for b, v in zip(bars, r["churn_rate"] * 100, strict=True):
        ax.text(b.get_x() + b.get_width() / 2, v + 0.5, f"{v:.1f}%", ha="center", fontsize=8)
    save(fig, name)
    return r


def main() -> None:
    raw = data.load_raw()
    blank_total = int((raw["TotalCharges"].astype("string").str.strip() == "").sum())
    df = data.clean(raw, require_target=True)
    enriched = features.add_features(df)
    n, churn_rate = len(df), df[config.TARGET].mean()

    # Figure 1: class balance
    fig, ax = plt.subplots(figsize=(4.5, 3.8))
    counts = df[config.TARGET].value_counts().sort_index()
    ax.bar(["Stayed", "Churned"], counts.values, color=[PALETTE[0], PALETTE[1]])
    ax.set_title("Class balance")
    for i, v in enumerate(counts.values):
        ax.text(i, v + 40, f"{v:,}", ha="center")
    save(fig, "eda_class_balance.png")

    contract = bar_rate(df, "Contract", "Churn rate by contract type", "eda_churn_by_contract.png")
    internet = rate_by(df, "InternetService")
    payment = bar_rate(df, "PaymentMethod", "Churn rate by payment method", "eda_churn_by_payment.png")
    tenure_g = bar_rate(
        enriched.assign(tenure_group=enriched["tenure_group"].astype(str)),
        "tenure_group",
        "Churn rate by tenure group",
        "eda_churn_by_tenure_group.png",
    )
    addons = rate_by(enriched, "n_addon_services")

    # Figure: distributions by churn
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8))
    for ax, col, title in zip(axes, ["tenure", "MonthlyCharges"], ["Tenure (months)", "Monthly charges ($)"], strict=True):
        for k, label in [(0, "Stayed"), (1, "Churned")]:
            ax.hist(df.loc[df[config.TARGET] == k, col], bins=30, alpha=0.6, label=label, color=PALETTE[k])
        ax.set_title(f"{title} by churn")
        ax.legend()
    save(fig, "eda_distributions.png")

    # Figure: numeric correlation
    num = enriched[config.NUMERIC_COLUMNS + features.ENGINEERED_NUMERIC + [config.TARGET]]
    corr = num.corr()
    fig, ax = plt.subplots(figsize=(6, 5))
    im = ax.imshow(corr, cmap="coolwarm", vmin=-1, vmax=1)
    ax.set_xticks(range(len(corr)), corr.columns, rotation=40, ha="right")
    ax.set_yticks(range(len(corr)), corr.columns)
    for i in range(len(corr)):
        for j in range(len(corr)):
            ax.text(j, i, f"{corr.iloc[i, j]:.2f}", ha="center", va="center", fontsize=7)
    fig.colorbar(im)
    ax.set_title("Correlation (numeric features and churn)")
    save(fig, "eda_correlation.png")

    med = df.groupby(config.TARGET)[["tenure", "MonthlyCharges"]].median()
    corr_target = corr[config.TARGET].drop(config.TARGET).sort_values(key=abs, ascending=False)

    def table(frame: pd.DataFrame) -> str:
        lines = ["| Group | Customers | Churn rate |", "|---|---:|---:|"]
        for idx, row in frame.iterrows():
            lines.append(f"| {idx} | {int(row['customers']):,} | {row['churn_rate'] * 100:.1f}% |")
        return "\n".join(lines)

    report = f"""# Exploratory Data Analysis Report

*Generated by `scripts/eda.py` from the actual dataset. Re-run the script to refresh every number.*

## Dataset
- **Source:** IBM Telco Customer Churn sample dataset (Apache-2.0).
- **Rows / columns:** {n:,} customers, {raw.shape[1]} columns.
- **Duplicate customer IDs:** {int(raw[config.ID_COLUMN].duplicated().sum())}.
- **Blank `TotalCharges` values:** {blank_total} (all stored as text; these are customers with tenure 0, treated as 0 charges so far).
- **Churn rate:** {churn_rate * 100:.1f}% ({int(counts[1]):,} churned vs {int(counts[0]):,} stayed), so the classes are imbalanced. Accuracy alone would be misleading, so evaluation uses ROC-AUC, precision, recall and F1.

![Class balance](../images/eda_class_balance.png)

## Churn by contract type
{table(contract)}

Highest-churn contract: **{contract.index[0]}** ({contract["churn_rate"].iloc[0] * 100:.1f}%); lowest: **{contract.index[-1]}** ({contract["churn_rate"].iloc[-1] * 100:.1f}%).

![Churn by contract](../images/eda_churn_by_contract.png)

## Churn by internet service
{table(internet)}

## Churn by payment method
{table(payment)}

![Churn by payment](../images/eda_churn_by_payment.png)

## Tenure
Median tenure: **{med.loc[1, "tenure"]:.0f} months** for churned customers vs **{med.loc[0, "tenure"]:.0f} months** for retained ones.

{table(tenure_g)}

![Churn by tenure group](../images/eda_churn_by_tenure_group.png)

## Charges and add-on services
Median monthly charge: **${med.loc[1, "MonthlyCharges"]:.2f}** (churned) vs **${med.loc[0, "MonthlyCharges"]:.2f}** (retained).

Churn rate by number of add-on services (security, backup, protection, support, streaming):

{table(addons)}

![Distributions](../images/eda_distributions.png)

## Correlation with churn (numeric features)
{chr(10).join(f"- `{k}`: {v:+.2f}" for k, v in corr_target.items())}

![Correlation](../images/eda_correlation.png)

## Implications for modelling
- Use stratified splits and report metrics beyond accuracy because of the class imbalance.
- Contract type, tenure and monthly charges carry clear signal, so they are central to the feature set.
- Engineered features added to the pipeline: `avg_monthly_spend`, `n_addon_services` and `tenure_group`.
- This is correlation in one company's sample data, not proof of cause.
"""
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(report, encoding="utf-8")
    print(f"Wrote {REPORT}")
    print(contract.round(3).to_string())
    print(tenure_g.round(3).to_string())


if __name__ == "__main__":
    main()
